#!/usr/bin/env python3
"""Copy the published operator docs from the Bongo code repository into docs/.

Usage: scripts/sync_docs.py [path-to-bongo-checkout]   (default: ../bongo)

For each file in DOCS it adds Jekyll front matter, rewrites repository-relative
links (to other docs pages on this site, or to GitHub for everything else) and
writes docs/<name>.md. It also writes _data/docs.yml, which the docs sidebar
reads. The file list and order live here and nowhere else.
"""
import pathlib
import re
import sys

REPO_URL = "https://github.com/bongo-project/bongo/blob/main/"

# Order is the sidebar order. Files not listed here are not published.
DOCS = [
    ("install", "Install"),
    ("dev-quickstart", "Development quick start"),
    ("walkthrough", "Walkthrough"),
    ("multi-domain-hosting", "Multi-domain hosting"),
    ("caldav-carddav", "CalDAV and CardDAV"),
    ("importing", "Importing mail"),
    ("sendmail", "bongo sendmail"),
    ("config-reload", "Config reload"),
    ("multi-node-cluster-checklist", "Multi-node cluster checklist"),
]
PUBLISHED = {name for name, _ in DOCS}

LINK = re.compile(r"\]\(([^)\s]+)\)")


def rewrite_link(target: str) -> str:
    if re.match(r"^[a-z][a-z0-9+.-]*:", target) or target.startswith("#") or target.startswith("/"):
        return target
    path, _, anchor = target.partition("#")
    anchor = "#" + anchor if anchor else ""
    if "/" not in path and path.endswith(".md") and path[:-3] in PUBLISHED:
        return "/docs/%s/%s" % (path[:-3], anchor)
    # Resolve relative to docs/ in the code repository.
    parts = []
    for seg in ("docs/" + path).split("/"):
        if seg == "..":
            if parts:
                parts.pop()
        elif seg not in ("", "."):
            parts.append(seg)
    return REPO_URL + "/".join(parts) + anchor


def yaml_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "../bongo").resolve()
    site = pathlib.Path(__file__).resolve().parent.parent
    out = site / "docs"
    out.mkdir(exist_ok=True)
    data = ["# Generated by scripts/sync_docs.py. Do not edit by hand."]
    for order, (name, nav) in enumerate(DOCS, start=1):
        text = (src / "docs" / (name + ".md")).read_text(encoding="utf-8")
        first = next((l for l in text.splitlines() if l.startswith("# ")), "# " + nav)
        title = first[2:].replace("`", "").strip()
        body = LINK.sub(lambda m: "](" + rewrite_link(m.group(1)) + ")", text)
        front = "\n".join([
            "---",
            "layout: doc",
            "title: " + yaml_str(title),
            "nav_title: " + yaml_str(nav),
            "permalink: /docs/%s/" % name,
            "source: " + REPO_URL + "docs/" + name + ".md",
            "---",
            "",
        ])
        # Docs may contain {{ }} or {% %} (Go templates, HCL); Liquid must not run on them.
        (out / (name + ".md")).write_text(front + "{% raw %}\n" + body.rstrip("\n") + "\n{% endraw %}\n", encoding="utf-8")
        data.append("- name: %s\n  title: %s\n  url: /docs/%s/" % (name, yaml_str(nav), name))
    (site / "_data").mkdir(exist_ok=True)
    (site / "_data" / "docs.yml").write_text("\n".join(data) + "\n", encoding="utf-8")
    print("synced %d docs from %s" % (len(DOCS), src))
    return 0


if __name__ == "__main__":
    sys.exit(main())
